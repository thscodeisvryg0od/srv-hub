let currentLang = localStorage.getItem("srv_lang") || "en";

function t(key, vars = {}) {
  const langData = i18n[currentLang] || i18n.en;
  let value = langData[key] || i18n.en[key] || key;
  Object.keys(vars).forEach(function (name) {
    value = value.replace(new RegExp("\\{" + name + "\\}", "g"), vars[name]);
  });
  return value;
}

function applyTranslations() {
  const data = i18n[currentLang] || i18n.en;
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    if (data[key] || i18n.en[key]) {
      el.textContent = data[key] || i18n.en[key];
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = data[key] || i18n.en[key] || el.placeholder;
  });
  document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-title");
    el.title = data[key] || i18n.en[key] || el.title;
  });
  document.documentElement.lang = currentLang;
}

window.i18n = i18n;
